function writeSubject(subject, items) {
  const edges = [];
  const relations = {};
  const seen = new Set();
  for (const it of items) {
    const k = `${it.edge.source}|${it.edge.target}|${it.edge.type}`;
    if (seen.has(k)) continue;
    seen.add(k);
    edges.push(it.edge);
    relations[it.relation.id] = it.relation;
  }
  const body = `/** Curated cross-topic links for ${subject} map */\nexport const CROSS_EDGES = ${JSON.stringify(edges, null, 2)};\nexport const CROSS_RELATIONS = ${JSON.stringify(relations, null, 2)};\n`;
  writeFileSync(join(ROOT, `data/${subject}/cross-links.js`), body);
  return edges.length;
}

