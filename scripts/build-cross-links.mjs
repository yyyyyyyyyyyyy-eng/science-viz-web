function rel(subject, source, target, type, typeZh, titleZh, summary, why, shared, example) {
  const [sCh, sCode] = source.split(':');
  const [tCh, tCode] = target.split(':');
  const id = `${source}=>${target}`;
  return {
    edge: { source, target, type },
    relation: {
      id, source, target, type, typeZh,
      sourceCode: sCode, targetCode: tCode,
      sourceHref: `#/t/${subject}/${sCh}/${sCode}`,
      targetHref: `#/t/${subject}/${tCh}/${tCode}`,
      titleZh, summary, why,
      shared: shared || [],
      example: example || '',
      steps: [
        `复习 ${sCode} 的核心定义/定律`,
        `指出它如何进入 ${tCode} 的推导或模型`,
        `完成一道同时用到二者的小题并自检`,
      ],
    },
  };
}

